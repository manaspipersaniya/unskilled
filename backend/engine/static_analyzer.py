"""Static, manifest and certificate analysis (tasks 1-5 of the brief)."""
import hashlib
import os
import re

from loguru import logger
from androguard.core.apk import APK

from . import permissions as perms

logger.remove()  # androguard is very chatty

ANDROID_NS = "{http://schemas.android.com/apk/res/android}"

# Package names of well-known legitimate apps that droppers impersonate.
KNOWN_LEGIT_PACKAGES = {
    "cn.wps.moffice_eng": "WPS Office", "com.ss.android.lark": "Lark", "com.wish.android": "Wish",
    "com.joom.app": "Joom", "com.douban.frodo": "Douban", "com.berrylook.android": "Berrylook",
    "com.netease.moba": "NetEase game", "com.whatsapp": "WhatsApp", "com.google.android.gms": "Google Play services",
    "com.android.vending": "Play Store", "com.facebook.katana": "Facebook", "com.instagram.android": "Instagram",
    "com.phonepe.app": "PhonePe", "net.one97.paytm": "Paytm", "com.sbi.lotusintouch": "SBI YONO",
}


def file_hashes(path):
    h = {"md5": hashlib.md5(), "sha1": hashlib.sha1(), "sha256": hashlib.sha256()}
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            for v in h.values():
                v.update(chunk)
    return {k: v.hexdigest() for k, v in h.items()}


def _components(apk, tag):
    """Return manifest components of a given tag with exported flag and intent filters."""
    out = []
    xml = apk.get_android_manifest_xml()
    target_sdk = int(apk.get_target_sdk_version() or 0)
    for node in xml.iter(tag):
        name = node.get(ANDROID_NS + "name") or ""
        if name.startswith("."):
            name = apk.get_package() + name
        filters = []
        for f in node.iter("intent-filter"):
            filters.append({
                "actions": [a.get(ANDROID_NS + "name") for a in f.iter("action")],
                "categories": [c.get(ANDROID_NS + "name") for c in f.iter("category")],
                "priority": f.get(ANDROID_NS + "priority"),
            })
        exported_attr = node.get(ANDROID_NS + "exported")
        if exported_attr is not None:
            exported = exported_attr == "true"
        else:  # pre-Android 12 implicit export when an intent filter is present
            exported = bool(filters) and target_sdk < 31
        out.append({
            "name": name,
            "exported": exported,
            "permission": node.get(ANDROID_NS + "permission"),
            "enabled": node.get(ANDROID_NS + "enabled") != "false",
            "intent_filters": filters,
            "meta": {m.get(ANDROID_NS + "name"): m.get(ANDROID_NS + "resource") or m.get(ANDROID_NS + "value")
                     for m in node.iter("meta-data")},
        })
    return out


def _certificate(apk):
    info = {"signed_v1": False, "signed_v2": False, "signed_v3": False, "certificates": [], "flags": []}
    try:
        info["signed_v1"] = apk.is_signed_v1()
        info["signed_v2"] = apk.is_signed_v2()
        info["signed_v3"] = apk.is_signed_v3()
        for c in apk.get_certificates():
            subject = c.subject.human_friendly
            issuer = c.issuer.human_friendly
            cert = {
                "subject": subject,
                "issuer": issuer,
                "serial": hex(c.serial_number),
                "not_before": str(c["tbs_certificate"]["validity"]["not_before"].native),
                "not_after": str(c["tbs_certificate"]["validity"]["not_after"].native),
                "sha1": c.sha1.hex(),
                "sha256": c.sha256.hex(),
                "algorithm": c.signature_algo,
                "key_size": c.public_key.bit_size,
                "self_signed": subject == issuer,
            }
            info["certificates"].append(cert)
            if "android@android.com" in subject:
                info["flags"].append("Signed with the public AOSP test key (anyone can sign with it)")
            cn = re.search(r"Common Name: ([^,]+)", subject)
            if cn and re.fullmatch(r"[A-Z0-9]{6}", cn.group(1)) and re.search(r"\d", cn.group(1)):
                info["flags"].append("Random-looking certificate subject (throwaway builder key)")
            if re.fullmatch(r"(Common Name: np, )?.*np.*", subject) and "Common Name: np" in subject:
                info["flags"].append("Certificate generated by NP Manager re-signing tool")
            if subject.strip() in ("Country: ID", "Country: US", "Country: CN"):
                info["flags"].append("Certificate subject contains only a country field")
    except Exception as e:  # malformed signatures are themselves an indicator
        info["flags"].append(f"Certificate parsing failed: {e}")
    if not (info["signed_v1"] or info["signed_v2"] or info["signed_v3"]):
        info["flags"].append("APK is not signed")
    return info


def analyze(path):
    """Run static/manifest/certificate analysis. Returns (APK object, result dict)."""
    apk = APK(path)
    size = os.path.getsize(path)
    pkg = apk.get_package()
    app_name = apk.get_app_name() or ""
    requested = apk.get_permissions()
    classified = perms.classify(requested)

    manifest = apk.get_android_manifest_xml()
    app_node = manifest.find("application")
    app_attrs = {}
    if app_node is not None:
        for k in ("debuggable", "allowBackup", "usesCleartextTraffic", "networkSecurityConfig", "name"):
            v = app_node.get(ANDROID_NS + k)
            if v is not None:
                app_attrs[k] = v

    components = {
        "activities": _components(apk, "activity") + _components(apk, "activity-alias"),
        "services": _components(apk, "service"),
        "receivers": _components(apk, "receiver"),
        "providers": _components(apk, "provider"),
    }

    flags = []
    if pkg in KNOWN_LEGIT_PACKAGES and KNOWN_LEGIT_PACKAGES[pkg].lower() not in app_name.lower():
        flags.append(f"Package name impersonates '{KNOWN_LEGIT_PACKAGES[pkg]}' but app is called '{app_name}'")
    if pkg.startswith(("com.android.", "android.", "com.google.android.")):
        flags.append("Package name mimics a system/Google component")
    if app_attrs.get("debuggable") == "true":
        flags.append("Application is debuggable")
    if app_attrs.get("usesCleartextTraffic") == "true":
        flags.append("Cleartext (HTTP) traffic allowed")
    launcher = [a for a in components["activities"]
                if any("android.intent.category.LAUNCHER" in f["categories"] for f in a["intent_filters"])]
    if not launcher:
        flags.append("No launcher activity (hidden icon / service-only app)")

    result = {
        "file_name": os.path.basename(path),
        "size": size,
        "hashes": file_hashes(path),
        "package": pkg,
        "app_name": app_name,
        "version_name": apk.get_androidversion_name(),
        "version_code": apk.get_androidversion_code(),
        "min_sdk": apk.get_min_sdk_version(),
        "target_sdk": apk.get_target_sdk_version(),
        "main_activity": apk.get_main_activity(),
        "application_attrs": app_attrs,
        "permissions": classified,
        "permission_summary": perms.summary(classified),
        "components": components,
        "exported_count": sum(1 for v in components.values() for c in v if c["exported"]),
        "certificate": _certificate(apk),
        "manifest_flags": flags,
        "manifest_xml": apk.get_android_manifest_axml().get_xml().decode("utf-8", "ignore"),
    }
    return apk, result

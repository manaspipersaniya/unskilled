"""Runs every analysis module on one APK and assembles a single result document."""
import time
import traceback

from . import static_analyzer, code_analyzer, network, evasion

SEVERITY_POINTS = {"high": 12, "medium": 6, "low": 2}

# ─── Benign-pattern helpers ────────────────────────────────────────────────────
# Code categories whose signal is weak when the app has no dangerous/suspicious
# permissions and a low obfuscation ratio (typical for F-Droid benign apps).
_LOW_CONTEXT_CATEGORIES = {
    "anti_debug", "anti_emulator", "shell_exec", "crypto_obfuscation",
    "dynamic_loading", "network", "surveillance",
}

# High-entropy file path fragments that are known-benign AOT / profiling
# artifacts generated by the Android runtime — not packed payloads.
_BENIGN_ENTROPY_FRAGMENTS = (
    "baseline.prof",
    ".vdex",
    "dexopt/",
    ".art",
    "odex",
    "classes.vdex",
    "boot.prof",
)


def _iocs(static, net):
    return {
        "hashes": static["hashes"],
        "package": static["package"],
        "file_name": static["file_name"],
        "certificate_sha256": [c["sha256"] for c in static["certificate"]["certificates"]],
        "urls": [u["url"] for u in net["urls"]],
        "domains": [d["domain"] for d in net["domains"]],
        "ips": [i["ip"] for i in net["ips"] if i["public"]],
        "cloud": net["cloud"],
    }


def _score(static, code, net, ev):
    """Additive, explainable risk score with calibration to reduce benign false-positives.

    Calibration rules applied after raw accumulation:
    - Code-category contributions are capped at 6 pts each when the app has no
      dangerous/suspicious permissions AND low obfuscation (benign F-Droid pattern).
    - Baseline AOT / profiling blobs (*.prof, *.vdex, dexopt/) are excluded from
      the high-entropy evasion score.
    - Level thresholds: Critical >= 85, High >= 68, Medium >= 30, Low < 30.
    """
    reasons = []

    # Permissions
    for p in static["permissions"]:
        if p["weight"] >= 5:
            reasons.append((p["weight"], f"Permission {p['short']}: {p['reason']}"))

    # Context flags used for calibration
    perm_summary = static.get("permission_summary", {})
    has_sus_perms = (perm_summary.get("dangerous", 0) + perm_summary.get("suspicious", 0)) > 0
    obf_ratio = code.get("obfuscation", {}).get("ratio", 0.0)
    low_obf = obf_ratio < 0.30  # >= 70% readable class names -> likely benign

    # Code / API findings
    in_code = {}
    for f in code["api_findings"]:
        if any(loc != "[string table]" for loc in f["locations"]):
            in_code[f["category"]] = in_code.get(f["category"], 0) + 1

    for cat, n in in_code.items():
        raw_pts = min(n, 4) * 2
        # Calibration: cap low-context categories for benign-looking apps
        if cat in _LOW_CONTEXT_CATEGORIES and not has_sus_perms and low_obf:
            raw_pts = min(raw_pts, 6)
        reasons.append((raw_pts, f"{n} code reference(s) in category '{cat}'"))

    # Evasion findings
    for f in ev["findings"]:
        # Skip high-entropy blobs that match known-benign AOT artifacts
        evidence_lower = (f.get("evidence") or "").lower()
        title_lower = f.get("title", "").lower()
        if "entropy" in title_lower or "encrypted" in title_lower:
            if any(frag in evidence_lower for frag in _BENIGN_ENTROPY_FRAGMENTS):
                continue  # exclude benign profiling artifact

        pts = SEVERITY_POINTS[f["severity"]]
        # Anti-debug / anti-emulator in low-obf, no-suspicious-perm apps -> halve
        if ("anti-debug" in title_lower or "anti-emulator" in title_lower):
            if not has_sus_perms and low_obf:
                pts = pts // 2
        reasons.append((pts, f"{f['title']}: {f['evidence'][:140]}"))

    # Manifest & certificate flags
    for flag in static["manifest_flags"] + static["certificate"]["flags"]:
        reasons.append((5, flag))

    # Network
    if net["counts"]["public_ips"]:
        reasons.append((3, f"{net['counts']['public_ips']} hard-coded public IP address(es)"))

    reasons.sort(key=lambda r: -r[0])
    score = min(100, sum(w for w, _ in reasons))

    # Calibrated level thresholds (raised vs original 80/55/30 to cut false-positive Highs)
    level = "Critical" if score >= 85 else "High" if score >= 68 else "Medium" if score >= 30 else "Low"

    return {
        "score": score,
        "level": level,
        "contributions": [{"points": w, "reason": r} for w, r in reasons[:40]],
    }


def analyze(path):
    started = time.time()
    errors = []
    _, static = static_analyzer.analyze(path)
    try:
        code = code_analyzer.analyze(path)
    except Exception:
        errors.append("code_analyzer: " + traceback.format_exc(limit=2))
        code = {"api_findings": [], "api_by_category": {}, "secrets": [], "obfuscation": {}, "_strings": set()}
    strings = code.pop("_strings", set())
    net = network.analyze(path, strings)
    ev = evasion.analyze(path)
    return {
        "static": static,
        "code": code,
        "network": net,
        "evasion": ev,
        "iocs": _iocs(static, net),
        "risk": _score(static, code, net, ev),
        "errors": errors,
        "duration_s": round(time.time() - started, 1),
    }
